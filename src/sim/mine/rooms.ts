/**
 * Ручные сегменты-комнаты (§4).
 *
 * Дизайн-документ прямо запрещает процедурную генерацию с нуля: комнаты рисуются
 * руками, а случайность — только в том, в каком порядке они склеиваются и какой
 * материал лежит в конкретной руде.
 *
 * Легенда:
 *   #  камень (твёрдый)
 *   .  пустота
 *   o  жила руды
 *   ^  шипы
 *   ~  ядовитая лужа
 *   c  осыпающаяся платформа
 *   s  сталактит (висит на потолке, падает под игроком)
 *
 * Стыковка: строки 12–15 у левого и правого края всегда пробиваются кодом,
 * так что соседние комнаты гарантированно соединяются коридором. Благодаря
 * этому сегменты можно рисовать свободно, не считая символы до края.
 */

export const ROOM_W = 36;
export const ROOM_H = 18;

/** Строки коридора-стыка. */
export const LINK_ROWS = [12, 13, 14, 15];

export interface RoomTemplate {
  name: string;
  /** Насколько комната опасна: 0 — спокойная, 2 — злая. Используется для отбора. */
  difficulty: number;
  rows: string[];
}

function parse(name: string, difficulty: number, art: string): RoomTemplate {
  const rows = art
    .split('\n')
    .map((r) => r.replace(/\s+$/, ''))
    .filter((r) => r.length > 0);
  return { name, difficulty, rows };
}

