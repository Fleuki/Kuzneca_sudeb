/**
 * Ручные сегменты-комнаты (§4).
 *
 * Дизайн-документ прямо запрещает процедурную генерацию с нуля: комнаты рисуются
 * руками, а случайность — только в том, в каком порядке они склеиваются и какой
 * материал лежит в конкретной руде.
 *
 * ГЛАВНОЕ ПРАВИЛО РИСОВАНИЯ. Платформы стоят только на ярусах 13, 10, 7 и 4 —
 * ступеньками через три тайла, ровно под высоту прыжка. По горизонтали соседние
 * ступени расходятся не больше чем на четыре тайла.
 *
 * Ряды 14 и 15 — сквозной коридор, и в них платформ не бывает: игрок ростом
 * в полтора тайла идёт по полу, и плита на 14-м ряду перекрыла бы ему проход
 * через всю комнату. Выше четвёртого ряда платформ тоже нет — игроку нужно два
 * свободных ряда над опорой, а сразу над ним потолок.
 *
 * Нарисовать недосягаемую платформу очень легко — в тексте она выглядит так же,
 * как достижимая. Первая версия комнат этим и страдала: 82% руды висело там,
 * куда нельзя было допрыгнуть. Поэтому есть `npm run mine-check`: он строит граф
 * мест, где можно стоять, и проверяет, что игрок дотянется до каждой жилы
 * и до подъёмника. Правки комнат гоняйте через него.
 *
 * Легенда:
 *   #  камень (твёрдый)
 *   .  пустота
 *   o  жила руды
 *   ^  шипы
 *   ~  ядовитая лужа
 *   c  осыпающаяся платформа
 *   s  сталактит (висит на потолке, падает под игроком)
 *
 * Стыковка: строки 12–15 у левого и правого края всегда пробиваются кодом,
 * так что соседние комнаты гарантированно соединяются коридором. Благодаря
 * этому сегменты можно рисовать свободно, не считая символы до края.
 */

export const ROOM_W = 36;
export const ROOM_H = 18;

/** Строки коридора-стыка. */
export const LINK_ROWS = [12, 13, 14, 15];

export interface RoomTemplate {
  name: string;
  /** Насколько комната опасна: 0 — спокойная, 2 — злая. Используется для отбора. */
  difficulty: number;
  rows: string[];
}

function parse(name: string, difficulty: number, art: string): RoomTemplate {
  const rows = art
    .split('\n')
    .map((r) => r.replace(/\s+$/, ''))
    .filter((r) => r.length > 0);
  return { name, difficulty, rows };
}

